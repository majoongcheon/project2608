/** 답을 못 낸 말머리. 이 한 곳만 보고 판별하도록 상수로 묶는다. */
const NO_ANSWER = '그건 제가 확실히 알지 못합니다.';

/**
 * 이 답이 "모르겠습니다"인가 — 화면이 미답변 질문을 가려내는 데 쓴다.
 * 글자를 화면 쪽에 복사해 두면 문구를 고칠 때 조용히 어긋난다.
 */
export function isFallback(r: BotReply): boolean {
  return r.text.startsWith(NO_ANSWER);
}

/** 모를 때. 지어내지 않고 사람에게 넘긴다 */
function fallback(): BotReply {
  return {
    text:
      NO_ANSWER + ' 잘못 알려 드리느니 모른다고 말씀드리는 편이 낫겠습니다.\n' +
      '이 서비스 안의 일(진단·결과·신청처·개인정보·즐겨찾기·후기)은 안내해 드릴 수 있고, 그 밖의 것은 ' + CENTER + '에 문의하시면 정확합니다.',
    suggestions: ['당신은 무엇을 답할 수 있나요?', '진단은 어떻게 하나요?', '신청처는 어떻게 찾나요?'],
  };
}

/** 견줄 때 쓰는 꼴 — 띄어쓰기·문장부호 차이로 어긋나지 않게 */
const norm = (s: string) => s.toLowerCase().replace(/[\s?!.,"'()·]/g, '');

/** 화면에서 누른 질문 → 규칙. 한 벌에서 만들어 두므로 어긋날 수 없다. */
const BY_ASK = new Map<string, Rule>();
for (const r of RULES) for (const a of r.asks) BY_ASK.set(norm(a), r);

/**
 * 답을 고른다.
 *   ① 화면에서 누른 질문은 글자 그대로 맞춰 그 규칙으로.
 *   ② 직접 적은 말은 열쇳말을 훑어 가장 긴 것이 이긴다 —
 *      '판정 불가' 가 '진단' 보다 구체적이므로 먼저 잡혀야 한다.
 */
export function answer(input: string): BotReply {
  const raw = input.toLowerCase().replace(/\s+/g, ' ').trim();
  if (!raw) return fallback();

  const exact = BY_ASK.get(norm(input));
  if (exact) return exact.reply;

  let best: { rule: Rule; score: number } | null = null;
  for (const rule of RULES) {
    for (const k of rule.keys) {
      if (raw.includes(k.toLowerCase())) {
        const score = k.length;
        if (!best || score > best.score) best = { rule, score };
      }
    }
  }
  return best ? best.rule.reply : fallback();
}

