/**
 * 규칙을 점수로 고른다. 가장 긴 열쇳말이 맞은 규칙이 이긴다 —
 * '판정 불가' 가 '진단' 보다 구체적이므로 먼저 잡혀야 한다.
 */
export function answer(input: string): BotReply {
  const q = input.toLowerCase().replace(/\s+/g, ' ').trim();
  if (!q) return fallback();

  let best: { rule: Rule; score: number } | null = null;
  for (const rule of RULES) {
    for (const k of rule.keys) {
      if (q.includes(k.toLowerCase())) {
        const score = k.length;
        if (!best || score > best.score) best = { rule, score };
      }
    }
  }
  return best ? best.rule.reply : fallback();
}
