//
// ── 왜 LLM 이 아닌가 ────────────────────────────────────────────────────────
// 이 저장소에는 LLM 도 API 키도 없다. 발표장에서 네트워크가 막히면 대화창이
// 통째로 빈 화면이 되는 위험을 지지 않기로 했다(기획자 결정, 15:30).
// 대신 우리가 실제로 아는 것만 답한다. 모르는 것은 지어내지 않고 모른다고
// 말하고 사람에게 넘긴다 — 복지 자격을 잘못 안내하는 것이 답을 못 하는 것보다
// 훨씬 나쁘다(헌법 원칙 I: 근거 기반).
//
// 나중에 LLM 을 붙일 자리: answer() 를 그대로 두고, 규칙에 걸리지 않은 말만
// 서버에 물어보도록 감싸면 된다. 화면은 바꿀 필요가 없다.
//
// ── 어떻게 고르는가 (16:10 개편) ───────────────────────────────────────────
// 규칙마다 `asks`(화면에 펼치는 질문)와 `keys`(자유 입력용 열쇳말)를 함께 둔다.
//   ① 화면에서 누른 질문은 `asks` 와 글자 그대로 맞춰 그 규칙으로 간다.
//   ② 직접 적은 말은 `keys` 를 부분 일치로 훑어 가장 긴 열쇳말이 이긴다.
// ①이 있어야 "형제자매도 지원을 받을 수 있나요?" 가 '받을 수 있' 에 걸려
// 이용 대상 안내로 새는 일이 구조적으로 막힌다(실제로 그랬다).
// 화면의 질문 목록(TOPICS)도 이 표에서 만들어지므로, 눌렀는데 엉뚱한 답이
// 나오거나 "모르겠습니다"가 나오는 일이 생길 수 없다.
//
// ── 지식의 출처 ────────────────────────────────────────────────────────────
// 숫자와 표현은 CLAUDE.md · specs/001-care-burden-map/spec.md · 화면에 실제로
// 쓰인 문구에서 가져왔다. 여기서 새로 만든 사실은 없다. 모르는 영역(신청 서류·
// 대기 기간·본인부담금 액수 등)은 모른다고 답하고 기관으로 넘긴다.

export interface BotReply {
  text: string;
  /** 이어서 물어볼 만한 것. 카카오톡의 빠른 답장처럼 단추로 낸다 */
  suggestions?: string[];
  /** 말보다 화면으로 가는 게 빠른 경우 */
  link?: { to: string; label: string };
}

interface Rule {
  id: string;
  /** 화면 질문 목록에서 어느 묶음에 들어가는지 */
  group: string;
  /** 화면에 펼치는 질문들. 글자 그대로 맞으면 이 규칙으로 온다 */
  asks: string[];
  /** 직접 적은 말을 잡는 열쇳말. 부분 일치, 긴 것이 이긴다 */
  keys: string[];
  reply: BotReply;
}

