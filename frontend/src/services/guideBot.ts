// 훨씬 나쁘다(헌법 원칙 I: 근거 기반).
//
// 나중에 LLM 을 붙일 자리: answer() 를 그대로 두고, 확신도(score)가 낮을 때만
// 서버에 물어보도록 감싸면 된다. 화면은 바꿀 필요가 없다.
//
// ── 지식의 출처 ────────────────────────────────────────────────────────────
