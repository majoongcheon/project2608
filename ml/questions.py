def build_question(feature: str, no: int) -> dict:
    """모델이 채택한 변수 하나를 화면 문항으로 옮긴다."""
    q = QUESTIONS[feature]
    is_cond = feature in CONDITIONAL
    opts = [{'value': v, 'label': l} for v, l in q.get('options', [])]
    if is_cond and 'options' in q:
        opts.append({'value': None, 'label': '해당사항 없음'})
    return {
        'questionNo': no,
        'feature': feature,
        'originalItem': q['item'],
        'text': q['text'],
        'inputType': q.get('type', 'choice'),
        'min': q.get('min'), 'max': q.get('max'), 'unit': q.get('unit'),
        'options': opts,
        'hasNotApplicable': is_cond,
        'explainTemplate': q['explain'],
    }
